"""Evaluation workflow: score the pipeline on the public samples and on custom cases, then write
code/evaluation/evaluation_report.md.

  python code/evaluation/main.py            (uses cached model answers only; makes no API calls)
"""
from __future__ import annotations

import json
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from audit.config import CODE_DIR, DATASET_DIR  # noqa: E402
from audit.llm import LLMClient, Ledger  # noqa: E402
from audit.pipeline import run_pipeline  # noqa: E402
from audit.store import ObservationStore  # noqa: E402
from evaluation import custom_cases  # noqa: E402
from evaluation.decisions import decision_metrics  # noqa: E402
from evaluation.linking import link_metrics  # noqa: E402
from evaluation.steps import load_answers, score  # noqa: E402

REPORT = CODE_DIR / "evaluation" / "evaluation_report.md"


def offline_client(tmp: Path) -> LLMClient:
    # Cached answers only, and a scratch ledger so evaluation runs never mix into usage accounting.
    return LLMClient(offline=True, ledger=Ledger(tmp / "ledger.jsonl"))


def evaluate_samples(tmp: Path) -> dict:
    llm = offline_client(tmp)
    store, _ = ObservationStore.build(DATASET_DIR, tmp / "samples.sqlite", llm)
    results = run_pipeline(store, llm)
    from audit.linker import Linker
    from evaluation.tie_signals import measure
    deletion_requests = [r for r in store.rows("SELECT * FROM requests") if results[r["case_id"]].intent[0]]
    linker = Linker(store)
    ties = measure(store, linker, deletion_requests, linker.link_cases(deletion_requests))
    store.con.close()
    gold_path = DATASET_DIR / "sample_output.csv"
    gold = load_answers(gold_path)
    predicted = {c: (r.status, r.steps) for c, r in results.items() if r.split == "sample"}
    cases = {c: r for c, r in results.items() if r.split == "sample"}
    links = {c: type("L", (), {"links": {d.resource_id: None for d in r.assessment.decisions}
                                if r.assessment else {}}) for c, r in cases.items()}
    assessments = {c: r.assessment for c, r in cases.items() if r.assessment}
    eval_cases = [r for r in results.values() if r.split == "eval"]
    return {
        "steps": score(predicted, gold),
        "links": link_metrics(links, gold_path),
        "decisions": decision_metrics(assessments, gold_path),
        "intent": {
            "non_deletion": sorted(c for c, r in results.items() if not r.intent[0]),
            "model_decided": sum("[llm" in r.intent[1] for r in results.values()),
            "disagreements": [(c, r.intent[1]) for c, r in results.items() if "rules disagree" in r.intent[1]],
            "total": len(results),
        },
        "ties": ties,
        "eval_status": {s: sum(r.status == s for r in eval_cases)
                        for s in ("COMPLETE", "INCOMPLETE", "NOT_APPLICABLE")},
    }


def evaluate_custom(tmp: Path) -> list[dict]:
    out = []
    for i, case in enumerate(custom_cases.CASES):
        data = custom_cases.build_dataset(DATASET_DIR, tmp / f"custom_{i}", case)
        # Screenshots are left out of the copies: no custom case depends on them, and offline
        # transcription is cached against the real dataset's files.
        store, _ = ObservationStore.build(data, tmp / f"custom_{i}.sqlite", None)
        results = run_pipeline(store, None)
        store.con.close()
        r = results[case.case_id]
        out.append({"case": case, "status": r.status, "steps": r.steps,
                    "problems": custom_cases.check(case, r.status, r.steps)})
    return out


def pct(x: float) -> str:
    return f"{100 * x:.1f}%"


def write_report(s: dict, custom: list[dict]) -> str:
    st, lk, dc, it = s["steps"], s["links"], s["decisions"], s["intent"]
    passed = sum(not c["problems"] for c in custom)
    lines = [
        "# Evaluation report",
        "",
        "Generated by `python code/evaluation/main.py` (offline: cached model answers, no API calls).",
        "The public samples were visible while the heuristics were designed, so sample scores are an upper",
        "bound; the custom cases and the eval-set notes below are the checks on generalization.",
        "",
        "## 1. Public samples (32 cases, full pipeline)",
        "",
        "| Metric | Score |",
        "|---|---|",
        f"| Case-level deletion-status accuracy | **{pct(st['status_accuracy'])}** |",
        f"| Step-level precision / recall / F1 (all fields incl. evidence_id) | "
        f"{st['step_exact']['precision']:.3f} / {st['step_exact']['recall']:.3f} / **{st['step_exact']['f1']:.3f}** |",
        f"| Step-level F1 ignoring evidence_id | {st['step_relaxed_no_evidence']['f1']:.3f} |",
        f"| Sequence accuracy: exact `steps_json` array match | **{pct(st['sequence_exact_match'])}** |",
        f"| Sequence accuracy: mean normalized edit similarity | {st['sequence_edit_similarity']:.3f} |",
        "",
        "Field-level accuracy (gold steps aligned to predicted steps by phase, resource and operation; a",
        "missing step counts as wrong on every field):",
        "",
        "| " + " | ".join(st["field_accuracy"]) + " |",
        "|" + "---|" * len(st["field_accuracy"]),
        "| " + " | ".join(pct(v) for v in st["field_accuracy"].values()) + " |",
        "",
        "Stage-level diagnostics:",
        "",
        "| Stage | Metric | Score |",
        "|---|---|---|",
        f"| Linking | resource recall / precision over the sample answers | {lk['recall']:.3f} / {lk['precision']:.3f} |",
        f"| State + policy | target state accuracy (linked records) | {pct(dc['target_accuracy'])} |",
        f"| State + policy | finding (violation) accuracy | {pct(dc['finding_accuracy'])} |",
        f"| State + policy | cited evidence accuracy | {pct(dc['evidence_accuracy'])} |",
        f"| Intent | model/rule agreement over {it['total']} requests | "
        f"{it['total'] - len(it['disagreements'])}/{it['total']} ({it['model_decided']} decided by the model) |",
        "",
        "### Remaining sample failures",
        "",
    ]
    for f in st["failures"]:
        lines.append(f"- `{f['case_id']}` (status {f['status'][0]} vs {f['status'][1]}): "
                     f"missing {[(m[2], m[3]) for m in f['missing']]}, extra {[(m[2], m[3]) for m in f['extra']]}")
    lines += [
        "",
        "Every remaining failure is one of two kinds, and none come from state, policy, ordering or citation:",
        "",
        "- **Unobservable resources** (`account_004`, `audit_record_5569`, `audit_record_6645`): they appear in no",
        "  participant-visible file, activity or screenshot, so no grounded method can produce them.",
        "- **Linking ties**: records with no identifiers left (deleted accounts, anonymized analytics) are tied to",
        "  a case through deletion-worker events. When several cases share a `reported_at` and their jobs report",
        "  the same result, the evidence cannot tell them apart (section 5); the linker records `contested-with=[...]` and",
        "  assigns deterministically instead of guessing from the labels.",
        "",
        f"## 2. Custom evaluation cases ({passed}/{len(custom)} pass)",
        "",
        "Built by `code/evaluation/custom_cases.py`: each copies the dataset, changes one thing, and states the",
        "expected effect from the contract before running.",
        "",
        "| Case | Behaviour under test | Expected | Got | Result |",
        "|---|---|---|---|---|",
    ]
    for c in custom:
        case = c["case"]
        lines.append(f"| `{case.name}` | {case.behaviour} | {case.expect_status} | {c['status']} | "
                     f"{'PASS' if not c['problems'] else 'FAIL: ' + '; '.join(c['problems'])} |")
    lines += ["", "Steps produced for each custom case:", ""]
    for c in custom:
        lines.append(f"- `{c['case'].name}`: " + (", ".join(
            f"{s['phase'][:4]} {s['operation']} {s['resource_id']} [{s['evidence_id']}]" for s in c["steps"]) or "[]"))
    ev = s["eval_status"]
    lines += [
        "",
        "## 3. Evaluation set (518 cases, no labels)",
        "",
        f"Status distribution: {ev['COMPLETE']} COMPLETE, {ev['INCOMPLETE']} INCOMPLETE, {ev['NOT_APPLICABLE']} "
        "NOT_APPLICABLE. Every row passes the contract validator (`audit/output.py`): header, 518 unique sorted",
        "rows, step schema and numbering, allowed operation/state pairs, phase order, evidence rules per status,",
        "and no citation of evidence captured after `audit_at`.",
        f"Non-deletion requests: {', '.join(i for i in it['non_deletion'] if not i.startswith('custom'))}.",
        "",
        "## 4. Failures found and improvements made",
        "",
        "| Failure found | How it was found | Fix |",
        "|---|---|---|",
        "| Pipe-delimited logs parsed as generic key=value, losing service and trace ids | dialect unit test | "
        "dialect regex accepts the leading `|`; each log file now resolves to exactly one dialect |",
        "| Strong identifier links alone found 76% of sample resources | linking recall on samples | "
        "workflow links from deletion-worker events in the request window + global one-owner assignment (93%) |",
        "| Overlapping request windows gave accounts to the wrong case | per-case link diffs | "
        "match account jobs to the workflow by its reported status (a matching feature, never proof) |",
        "| Snapshot bundles captured after audit_at leaked in through their internal timestamps | evidence "
        "accuracy 53% | eligibility uses the manifest capture time |",
        "| Partial bundles 'proved' other people's records absent | retained audit records reported missing | "
        "bundle absence only counts for subjects the bundle includes; SQL dumps are full captures |",
        "| A primary-side capture hid a failover ghost copy | case_05 | state is tracked per location; present in any location means present |",
        "| A catalog link was treated as proof a record exists | extra steps for `object_19`, `tombstone_17` | "
        "activity fallback only uses state-changing events |",
        "| Retained security records without evidence were dropped | missing VERIFY_RECORD_PRESENT steps | "
        "account and retained records are always planned; partial captures never prove their absence |",
        "| A case with nothing verifiable would be claimed COMPLETE | validator: COMPLETE without steps | "
        "unproven required states keep a case INCOMPLETE |",
        "| Older explicit absences outranked a later sighting of the record | custom case `earlier-cleanup-counts` | "
        "only absences after the last sighting can prove deletion |",
        "| Vision model wrote `user_11 - account_5762` into one field; strict validation dropped the id | "
        "screenshot probe | ids extracted with the evidence regexes; referenced records kept as linked sightings |",
        "| Undocumented free-tier cap of 1,000 output tokens/minute (429) and a dense screen truncating at the "
        "token limit (400) | live ledger | output-token window in the guard; compact retry; truncation cached so it is never repeated |",
        "| Intent batches of 25 silently dropped the last items at the token limit | items answered vs asked | "
        "batches of 30 with a minimal schema, and a second round re-asks any skipped item |",
        "| Custom cases about the same person saw each other's added evidence (2 false failures) | "
        "custom-case results | each custom case runs on its own isolated dataset copy |",
        "| Ties were flagged for every case whose window held the event (315 of 392 links), hiding which "
        "were really undecidable | tie analysis | `contested-with` lists only rivals with the same result "
        "evidence that lack, or could swap, a record of that kind |",
        "",
    ]
    from evaluation.tie_signals import report_lines
    lines += report_lines(s["ties"])
    text = "\n".join(lines)
    REPORT.write_text(text, encoding="utf-8")
    return text


def main() -> int:
    with tempfile.TemporaryDirectory(ignore_cleanup_errors=True) as tmp:
        tmp_path = Path(tmp)
        samples = evaluate_samples(tmp_path)
        custom = evaluate_custom(tmp_path)
    write_report(samples, custom)
    summary = {k: v for k, v in samples["steps"].items() if k != "failures"}
    print(json.dumps(summary, indent=2))
    for c in custom:
        print(f"custom {c['case'].name}: {'PASS' if not c['problems'] else c['problems']}")
    print(f"wrote {REPORT}")
    return 0 if all(not c["problems"] for c in custom) else 1


if __name__ == "__main__":
    sys.exit(main())
